/* Shared app shell + variant switcher. Variant agents never edit this.
   A variant page provides <aside id="shell-nav"></aside> and loads, in order:
   tokens.css, data.js, variants.js, shell-config.js, then this file.

   window.SHELL (shell-config.js) must reproduce EVERY control the real shell has:
     { app: "Acme Admin", current: "events",
       user: { name: "김민지", email: "minji@example.com", role: "admin" },
       nav: [{ id: "events", label: "행사", href: "pages/events/a-x.html", roles: ["admin", "staff"] }],
       controls: ["collapse", "theme", "fontSize", "password", "logout"] }
   nav hrefs are relative to the redesign root. ?role=<role> previews a restricted role.
   window.VARIANTS (variants.js) is generated by build_index.py; don't hand-edit it.
   ?shot=1 hides the switcher (shot.mjs and probe.mjs add it).
   window.toast(msg) is for stubbed actions, so no button is ever dead. */
(() => {
  const ROOT = new URL('..', document.currentScript.src);
  const params = new URLSearchParams(location.search);
  const cfg = window.SHELL || { app: 'App', nav: [], user: { name: 'User', role: 'admin' }, controls: [] };
  const role = params.get('role') || cfg.user.role;
  const has = (c) => (cfg.controls || []).includes(c);
  const store = (k, v) => (v === undefined ? localStorage.getItem('rd.' + k) : localStorage.setItem('rd.' + k, v));

  const css = `
  #shell-nav{width:var(--nav-w);flex:none;display:flex;flex-direction:column;border-right:1px solid var(--c-border);background:var(--c-surface);transition:width 160ms var(--ease-out)}
  .shell-collapsed #shell-nav{width:var(--nav-w-collapsed)}
  .sn-head{height:var(--header-h);display:flex;align-items:center;gap:var(--s-2);padding:0 var(--s-4);font-weight:600}
  .sn-list{flex:1;min-height:120px;overflow:auto;padding:var(--s-2)}
  .sn-foot{overflow:auto}
  .sn-item{display:flex;align-items:center;gap:var(--s-3);height:36px;padding:0 var(--s-3);border-radius:var(--r-sm);color:var(--c-text-2);text-decoration:none;font-size:var(--t-sm);white-space:nowrap;overflow:hidden}
  .sn-item:hover{background:var(--c-border)}
  .sn-item[aria-current=page]{background:var(--c-bg);color:var(--c-text);font-weight:600}
  .sn-ico{width:20px;flex:none;text-align:center}
  .shell-collapsed .sn-label,.shell-collapsed .sn-app{display:none}
  .sn-foot{border-top:1px solid var(--c-border);padding:var(--s-2);display:flex;flex-direction:column;gap:2px}
  .sn-foot button{all:unset;cursor:pointer;display:flex;align-items:center;gap:var(--s-3);height:32px;padding:0 var(--s-3);border-radius:var(--r-sm);font-size:var(--t-sm);color:var(--c-text-2);white-space:nowrap;overflow:hidden}
  .sn-foot button:hover{background:var(--c-border)}
  .sn-user{padding:var(--s-2) var(--s-3);font-size:var(--t-xs);color:var(--c-text-2);white-space:nowrap;overflow:hidden;text-overflow:ellipsis}
  .shell-collapsed .sn-user{display:none}
  .vs{position:fixed;top:8px;left:50%;transform:translateX(-50%);z-index:9999;display:flex;align-items:center;gap:4px;padding:3px;border-radius:999px;background:rgba(24,24,27,.88);color:#fff;font:500 12px/1 -apple-system,system-ui,sans-serif;box-shadow:0 4px 16px rgba(0,0,0,.18)}
  .vs button,.vs select{all:unset;cursor:pointer;height:24px;padding:0 8px;border-radius:999px}
  .vs button:hover,.vs select:hover{background:rgba(255,255,255,.14)}
  .vs select{max-width:320px;text-overflow:ellipsis;overflow:hidden;white-space:nowrap}
  .vs option{color:#18181b}
  .shell-toast{position:fixed;left:50%;bottom:24px;transform:translateX(-50%);background:var(--c-text);color:var(--c-bg);padding:8px 14px;border-radius:var(--r-md);font-size:var(--t-sm);z-index:9999;transition:opacity 160ms var(--ease-out)}
  dialog.shell-dlg{border:1px solid var(--c-border);border-radius:var(--r-md);padding:var(--s-5);width:360px;background:var(--c-bg);color:var(--c-text)}
  dialog.shell-dlg form{display:flex;flex-direction:column;gap:var(--s-3)}`;
  document.head.insertAdjacentHTML('beforeend', `<style>${css}</style>`);

  window.toast = (msg) => {
    const t = document.createElement('div');
    t.className = 'shell-toast';
    t.textContent = msg;
    document.body.append(t);
    setTimeout(() => { t.style.opacity = '0'; setTimeout(() => t.remove(), 200); }, 1800);
  };

  const theme = store('theme');
  if (theme) document.documentElement.dataset.theme = theme;
  const scale = store('fontScale');
  if (scale) document.documentElement.style.setProperty('--font-scale', scale);
  if (store('collapsed') === '1') document.documentElement.classList.add('shell-collapsed');

  const nav = document.getElementById('shell-nav');
  if (nav) {
    nav.setAttribute('data-chrome', '');
    const items = (cfg.nav || [])
      .filter((n) => !n.roles || n.roles.includes(role))
      .map((n) => `<a class="sn-item" href="${new URL(n.href || '#', ROOT).href}" ${n.id === cfg.current ? 'aria-current="page"' : ''} title="${n.label}"><span class="sn-ico">${n.icon || '•'}</span><span class="sn-label">${n.label}</span></a>`)
      .join('');
    const foot = [
      has('collapse') && `<button data-act="collapse"><span class="sn-ico">⇤</span><span class="sn-label">메뉴 접기</span></button>`,
      has('theme') && `<button data-act="theme"><span class="sn-ico">◐</span><span class="sn-label">테마</span></button>`,
      has('fontSize') && `<button data-act="font"><span class="sn-ico">가</span><span class="sn-label">글자 크기</span></button>`,
      has('password') && `<button data-act="password"><span class="sn-ico">＊</span><span class="sn-label">비밀번호 변경</span></button>`,
      has('logout') && `<button data-act="logout"><span class="sn-ico">↩</span><span class="sn-label">로그아웃</span></button>`,
    ].filter(Boolean).join('');
    nav.innerHTML = `<div class="sn-head"><span class="sn-ico">${cfg.logo || '◆'}</span><span class="sn-app">${cfg.app}</span></div>
      <nav class="sn-list">${items}</nav>
      <div class="sn-foot"><div class="sn-user">${cfg.user.name} · ${role}</div>${foot}</div>`;
    nav.addEventListener('click', (e) => {
      const act = e.target.closest('[data-act]')?.dataset.act;
      if (act === 'collapse') store('collapsed', document.documentElement.classList.toggle('shell-collapsed') ? '1' : '0');
      if (act === 'theme') {
        const next = document.documentElement.dataset.theme === 'dark' ? 'light' : 'dark';
        document.documentElement.dataset.theme = next;
        store('theme', next);
      }
      if (act === 'font') {
        const steps = ['0.9', '1', '1.15'];
        const next = steps[(steps.indexOf(store('fontScale') || '1') + 1) % steps.length];
        document.documentElement.style.setProperty('--font-scale', next);
        store('fontScale', next);
        toast(`글자 크기 ${Math.round(next * 100)}%`);
      }
      if (act === 'password') {
        const d = document.createElement('dialog');
        d.className = 'shell-dlg';
        d.innerHTML = `<form method="dialog"><strong>비밀번호 변경</strong><input class="input" type="password" placeholder="현재 비밀번호"><input class="input" type="password" placeholder="새 비밀번호"><div style="display:flex;gap:8px;justify-content:flex-end"><button class="btn" value="cancel">취소</button><button class="btn btn-primary" value="ok">변경</button></div></form>`;
        document.body.append(d);
        d.addEventListener('close', () => { if (d.returnValue === 'ok') toast('비밀번호를 변경했어요'); d.remove(); });
        d.showModal();
      }
      if (act === 'logout') toast('로그아웃 (프로토타입)');
    });
  }

  // Variant switcher: top centre, so it never covers sticky footers or save buttons.
  const all = window.VARIANTS || [];
  if (all.length && !params.has('shot')) {
    const here = location.pathname.split('/').slice(-3).join('/');
    const idx = Math.max(0, all.findIndex((v) => here.endsWith(v.href)));
    const go = (i) => { location.href = new URL(all[(i + all.length) % all.length].href, ROOT).href + location.search; };
    const groups = [...new Set(all.map((v) => v.page))];
    const vs = document.createElement('nav');
    vs.className = 'vs';
    vs.setAttribute('data-chrome', '');
    vs.innerHTML = `<button title="Previous ([)">‹</button><select>${groups.map((g) => `<optgroup label="${g}">${all.map((v, i) => v.page === g ? `<option value="${i}" ${i === idx ? 'selected' : ''}>${v.label}${v.recommended ? ' ★' : ''}</option>` : '').join('')}</optgroup>`).join('')}</select><button title="Next (])">›</button><button title="Index">≡</button>`;
    const [prev, sel, next, home] = vs.children;
    prev.onclick = () => go(idx - 1);
    next.onclick = () => go(idx + 1);
    sel.onchange = () => go(+sel.value);
    home.onclick = () => { location.href = new URL('index.html', ROOT).href; };
    addEventListener('keydown', (e) => {
      if (e.target.closest('input, textarea, select, [contenteditable]')) return;
      if (e.key === '[') go(idx - 1);
      if (e.key === ']') go(idx + 1);
    });
    document.body.append(vs);
  }
})();
